function format(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''))
}

export function msg(key: MsgKey, vars?: Record<string, string | number>) {
  return format(translations[currentLang][key], vars)
}

export type MsgKey = keyof typeof translations.tr
